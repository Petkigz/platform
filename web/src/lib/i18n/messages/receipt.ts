/**
 * The receipt (`app/orders/[id]/receipt/page.tsx`): the document a payer
 * keeps, and the page every line of my orders and of the statement leads to.
 *
 * Same rule as `learn.ts`, `course.ts`, `lesson.ts`, `assess.ts`, `assign.ts`,
 * `missing.ts`, `broke.ts`, `player.ts`, `account.ts`, `family.ts`, `buy.ts`,
 * `close.ts`, `export.ts`, `reading.ts`, `restore.ts`, `phone.ts`, `merge.ts`,
 * `share.ts`, `refer.ts`, `sponsor.ts`, `orders.ts` and `billing.ts`: written
 * for the twenty-seven languages with nothing held in `held.ts`, and for no
 * other. See `UNWRITTEN_WHILE_HELD`.
 *
 * **An order that has not been paid is not a receipt, and says so.**
 * `notLead` and `notBody` are said above it, its title is "order" and its
 * total is `totalDue`, "to pay". `totalPaid` and `paidOn` are said of a
 * settled order and of nothing else. A translation of `totalDue` that reads
 * as "paid" is wrong.
 *
 * **It says what the platform knows.** `notBody` is "no payment has been
 * confirmed", not "nothing has been charged": while a payment is being
 * confirmed the payer may already have approved it on a handset, and a
 * document that told them nothing had left their wallet would be wrong.
 *
 * **Most of the sheet is borrowed.** An order's state, the parts of a total
 * and the date it was placed are my orders' (`orders.st…`, `orders.ln…`,
 * `orders.placedOn`), and a refund and what it has reached are the
 * statement's (`billing.wtRefund`, `billing.rfPending`, `billing.rfFailed`,
 * `billing.mvReturned`), so the three pages cannot name one thing two ways.
 *
 * **What is put in comes last, after a colon**, so that no language has to
 * inflect it: a number, a name, a date, an amount as a currency code and
 * digits, a payment service's own name and its reference.
 *
 * **Nobody is given a gender.** `forLearner` is "for", not "the learner",
 * in the languages where that word would have to be one or the other.
 *
 * **Served to the server only.** `receipt.` is in `SERVER_ONLY_PREFIXES`: the
 * one button on the page is handed its word by the page.
 *
 * **Unreviewed.** No speaker has read any of these.
 */
