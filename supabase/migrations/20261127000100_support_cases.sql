-- Resolving says what was done. A resolved case with no note is an unanswered
-- case with a green badge on it.
create or replace function public.resolve_support_case(
  p_case_id uuid,
  p_note    text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := public.current_user_id();
  v_case  public.support_cases;
begin
  if v_actor is null or not public.is_privileged(v_actor) then
    raise exception 'only staff may resolve a support case'
      using errcode = 'insufficient_privilege';
  end if;

  select * into v_case from public.support_cases where id = p_case_id;
  if v_case.id is null then
    raise exception 'support case not found' using errcode = 'P0002';
  end if;

  if v_case.status = 'closed' then
    raise exception 'a closed case cannot be resolved' using errcode = 'check_violation';
  end if;

  if coalesce(trim(p_note), '') = '' then
    raise exception 'say how this was resolved — the requester reads it'
      using errcode = 'check_violation';
  end if;

  update public.support_cases
     set status = 'resolved',
         resolved_by = v_actor,
         resolved_at = now(),
         resolution_note = trim(p_note)
   where id = p_case_id;

  insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
  values (v_actor, 'support_case.resolved', 'support_case', p_case_id,
          jsonb_build_object('from_status', v_case.status));
end;
$$;
revoke execute on function public.resolve_support_case(uuid, text) from public;
grant execute on function public.resolve_support_case(uuid, text) to authenticated;

-- Closing is terminal: no further replies from either side. Two callers, one
-- rule — staff closing a case, or a requester withdrawing their own.
create or replace function public.close_support_case(
  p_case_id uuid,
  p_reason  text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := public.current_user_id();
  v_case  public.support_cases;
  v_is_staff boolean;
begin
  if v_actor is null then
    raise exception 'sign in to close a case' using errcode = 'insufficient_privilege';
  end if;

  select * into v_case from public.support_cases where id = p_case_id;
  if v_case.id is null then
    raise exception 'support case not found' using errcode = 'P0002';
  end if;

  select public.is_privileged(v_actor) into v_is_staff;

  if not (v_is_staff or v_case.requested_by = v_actor) then
    raise exception
      'you cannot close somebody else''s case'
      using errcode = 'insufficient_privilege';
  end if;

  if v_case.status = 'closed' then
    raise exception 'this case is already closed' using errcode = 'check_violation';
  end if;

  if coalesce(trim(p_reason), '') = '' then
    raise exception 'give a reason for closing' using errcode = 'check_violation';
  end if;

  update public.support_cases
     set status = 'closed',
         closed_by = v_actor,
         closed_at = now(),
         close_reason = trim(p_reason)
   where id = p_case_id;

  insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
  values (v_actor, 'support_case.closed', 'support_case', p_case_id,
          jsonb_build_object('reason', trim(p_reason), 'from_status', v_case.status,
                             'by_requester', not v_is_staff));
end;
$$;
revoke execute on function public.close_support_case(uuid, text) from public;
grant execute on function public.close_support_case(uuid, text) to authenticated;

