-- =============================================================================
-- AyahSpring — the help desk: support cases and replies
--
-- Screen 43 was recorded as "BLOCKED — 7 endpoints, no `support_cases` table".
-- Those endpoints were part of the original API sketch and were never built
-- here, so nothing in this repository referenced the table; the block was real
-- but it was an absence, not a break. `platform.support` is an ADMIN-gated
-- flag, so the whole channel can be built now and switched on from the
-- dashboard when someone is available to answer it.
--
-- The design decisions, stated because they are the parts that are easy to get
-- wrong in a help desk attached to a platform that teaches children:
--
--   * **A case is opened by a signed-in account, never anonymously.** Support
--     replies have to reach somebody, and an anonymous channel is a queue
--     nobody can close. `content_reports` already covers "this lesson is wrong"
--     from someone who will not sign in; this is the other direction.
--   * **Case numbers are human.** `SC-000123`, from a sequence, not a uuid.
--     Support is a conversation that happens partly outside the product — in an
--     email or a WhatsApp thread — and a uuid cannot be read aloud.
--   * **Internal notes exist and are staff-only.** Agents need to write down
--     what they checked without publishing it to the person asking. The
--     requester can never read one, and can never write one.
--   * **Turning the flag off stops new cases, not the work in flight.** Staff
--     can still reply, resolve and close cases that are already open. A kill
--     switch that strands live conversations is worse than no kill switch.
--   * **A requester who replies to a resolved case reopens it.** The
--     alternative — "thank you, that fixed it" and "no it did not" both leaving
--     the case resolved — is how a help desk reports a resolution rate it has
--     not earned.
--   * **Five open cases is the ceiling per account.** Same reasoning as the
--     one-open-report-per-person index: this queue is read by people.
--
-- Nothing here sends an email or a push notification. `delivery.notifications`
-- is a separate, CODE-gated flag with no provider chosen, and this migration
-- does not pretend otherwise.
-- =============================================================================

-- The flag register described a table that did not exist. Bring the row in line
-- with what is now true; `value_text` is untouched, so the flag still ships off.
update public.platform_settings
   set description   = 'Support cases and replies',
       preconditions = 'Someone available to answer the queue; reply-channel and retention policy decided. No notification provider is wired — cases are read in the dashboard.'
 where key = 'platform.support';

-- -----------------------------------------------------------------------------
-- 1. Cases
-- -----------------------------------------------------------------------------

create sequence if not exists public.support_case_number_seq;

create table public.support_cases (
  id uuid primary key default gen_random_uuid(),

  -- Read aloud in an email thread. Generated by open_support_case().
  case_number text not null,

  -- The account that asked. Taken from the session, never from the request.
  requested_by uuid not null
    references public.user_profiles (user_id) on delete restrict,

  -- Optional context, both checked against the requester's own access:
  -- a parent asking about a child, or a customer asking about a payment.
  learner_profile_id uuid
    references public.learner_profiles (id) on delete restrict,
  order_id uuid
    references public.orders (id) on delete restrict,

  category text not null
    check (category in
      ('account', 'payment', 'access', 'content', 'certificate', 'family', 'other')),

  subject text not null check (length(trim(subject)) between 3 and 200),
  body    text not null check (length(trim(body)) between 1 and 4000),

  status text not null default 'open'
    check (status in ('open', 'assigned', 'waiting_on_user', 'resolved', 'closed')),

  -- Staff-set. A requester cannot make their own case urgent.
  priority text not null default 'normal'
    check (priority in ('low', 'normal', 'high', 'urgent')),

  assigned_to uuid references public.user_profiles (user_id) on delete set null,
  assigned_by uuid references public.user_profiles (user_id) on delete set null,
  assigned_at timestamptz,

  resolved_by uuid references public.user_profiles (user_id) on delete set null,
  resolved_at timestamptz,
  resolution_note text,

  closed_by uuid references public.user_profiles (user_id) on delete set null,
  closed_at timestamptz,
  close_reason text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- D7: a support conversation is a record. There is no deleted_at; `closed`
  -- is the end of a case, not its removal.
  constraint sc_assigned_together check (
    (assigned_to is null) = (assigned_at is null)
  ),
  constraint sc_resolved_together check (
    (resolved_by is null) = (resolved_at is null)
  ),
  constraint sc_resolved_needs_note check (
    resolved_at is null or length(trim(coalesce(resolution_note, ''))) > 0
  ),
  constraint sc_closed_needs_reason check (
    closed_at is null or length(trim(coalesce(close_reason, ''))) > 0
  ),
  -- A resolved case has been resolved; a closed case has an end. Asserting the
  -- pairing stops a row claiming a status its timestamps contradict.
  constraint sc_status_matches_resolution check (
    (status = 'resolved') = (resolved_at is not null and closed_at is null)
  ),
  constraint sc_status_matches_closure check (
    (status = 'closed') = (closed_at is not null)
  ),
  constraint sc_status_matches_assignment check (
    (status = 'assigned') = (assigned_to is not null and resolved_at is null
                             and closed_at is null)
  )
);

create unique index support_cases_number_key on public.support_cases (case_number);
create index support_cases_requester_idx
  on public.support_cases (requested_by, created_at desc);
create index support_cases_queue_idx
  on public.support_cases (priority, created_at)
  where status in ('open', 'assigned', 'waiting_on_user');

create trigger support_cases_set_updated_at
  before update on public.support_cases
  for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------------------
-- 2. Messages
-- -----------------------------------------------------------------------------

create table public.support_case_messages (
  id uuid primary key default gen_random_uuid(),

  case_id uuid not null
    references public.support_cases (id) on delete restrict,

  author_user_id uuid not null
    references public.user_profiles (user_id) on delete restrict,

  -- Set by the writer from who the author actually is, never from the request.
  author_kind text not null default 'requester'
    check (author_kind in ('requester', 'staff')),

  body text not null check (length(trim(body)) between 1 and 4000),

  -- Staff-only annotation. Invisible to the requester in the read policy, and
  -- unwritable by one in the writer function.
  is_internal boolean not null default false,

  created_at timestamptz not null default now(),

  -- Only staff write internal notes; a requester's message is never one.
  constraint scm_internal_is_staff check (
    not is_internal or author_kind = 'staff'
  )
);

create index support_case_messages_case_idx
  on public.support_case_messages (case_id, created_at);

-- -----------------------------------------------------------------------------
-- 3. Row level security
--
-- Reads only. Every write goes through a function below, which is where the
-- identity and state rules live — a policy that allows an update cannot say
-- "only staff, only with a reason, only from these states".
-- -----------------------------------------------------------------------------

alter table public.support_cases enable row level security;
alter table public.support_case_messages enable row level security;

create policy support_cases_read on public.support_cases
  for select to authenticated
  using (
    requested_by = public.current_user_id()
    or public.is_privileged(public.current_user_id())
  );

-- An internal note stays inside the team even from the person who opened the
-- case. A staff member who opens their own case can still read them: internal
-- notes are staff information, and they are staff.
create policy support_case_messages_read on public.support_case_messages
  for select to authenticated
  using (exists (
    select 1 from public.support_cases sc
     where sc.id = support_case_messages.case_id
       and (
         public.is_privileged(public.current_user_id())
         or (sc.requested_by = public.current_user_id()
             and not support_case_messages.is_internal)
       )
  ));

-- No insert, update or delete policies on either table, and no DML grant:
-- the functions are SECURITY DEFINER and run as the table owner, which is the
-- same arrangement `issue_certificate()` already uses.
--
-- The revoke names `authenticated` explicitly. A hosted Postgres usually grants
-- every privilege on new public tables to it by default, so "I never granted
-- insert" is not the same as "insert is refused" — and RLS with no insert
-- policy would refuse it anyway, but the two should agree rather than one
-- covering for the other.
revoke all on public.support_cases, public.support_case_messages
  from public, anon, authenticated;
grant select on public.support_cases, public.support_case_messages to authenticated;

-- -----------------------------------------------------------------------------
-- 4. Who is answering
-- -----------------------------------------------------------------------------

create or replace function public.can_read_support_case(p_case_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_privileged(public.current_user_id())
      or exists (
        select 1 from public.support_cases sc
         where sc.id = p_case_id
           and sc.requested_by = public.current_user_id()
      );
$$;
revoke all on function public.can_read_support_case(uuid) from public;
grant execute on function public.can_read_support_case(uuid) to authenticated;

comment on function public.can_read_support_case(uuid) is
  'The account that opened the case, or staff. Used by the writer functions; reads are handled by RLS.';

-- -----------------------------------------------------------------------------
-- 5. Opening a case
-- -----------------------------------------------------------------------------

create or replace function public.open_support_case(
  p_category           text,
  p_subject            text,
  p_body               text,
  p_learner_profile_id uuid default null,
  p_order_id           uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := public.current_user_id();
  v_order public.orders;
  v_id    uuid;
  v_open  integer;
begin
  if v_actor is null then
    raise exception 'sign in to ask for help' using errcode = 'insufficient_privilege';
  end if;

  -- Off means off for new cases. Deliberately not applied to the staff
  -- functions below: switching the feature off must not strand a conversation
  -- that is already in flight.
  if not public.setting_bool('platform.support', false) then
    raise exception
      'support is not open yet (platform.support is off)'
      using errcode = 'check_violation';
  end if;

  if p_category not in
    ('account', 'payment', 'access', 'content', 'certificate', 'family', 'other') then
    raise exception 'unsupported support category: %', coalesce(p_category, '(none)')
      using errcode = 'check_violation';
  end if;

  if length(trim(coalesce(p_subject, ''))) < 3 then
    raise exception 'add a short subject so the team knows what this is about'
      using errcode = 'check_violation';
  end if;

  if coalesce(trim(p_body), '') = '' then
    raise exception 'describe the problem'
      using errcode = 'check_violation';
  end if;

  -- A parent asking about a child has to be able to act for that child, and a
  -- customer asking about an order has to be on its billing account. Without
  -- this a case id becomes a way to attach somebody else's context to your own
  -- request and have a stranger's details discussed in your thread.
  if p_learner_profile_id is not null
     and not public.can_access_learner(p_learner_profile_id) then
    raise exception
      'you cannot attach a learner you do not have access to'
      using errcode = 'insufficient_privilege';
  end if;

  if p_order_id is not null then
    select * into v_order from public.orders where id = p_order_id;
    if v_order.id is null then
      raise exception 'order not found' using errcode = 'P0002';
    end if;
    if not public.is_billing_member(v_order.billing_account_id) then
      raise exception
        'you are not on the billing account for this order'
        using errcode = 'insufficient_privilege';
    end if;
  end if;

  select count(*) into v_open
    from public.support_cases
   where requested_by = v_actor
     and status in ('open', 'assigned', 'waiting_on_user');
  if v_open >= 5 then
    raise exception
      'you already have five open requests; wait for a reply or close one first'
      using errcode = 'check_violation';
  end if;

  insert into public.support_cases
    (case_number, requested_by, learner_profile_id, order_id,
     category, subject, body, status, priority)
  values
    ('SC-' || lpad(nextval('public.support_case_number_seq')::text, 6, '0'),
     v_actor, p_learner_profile_id, p_order_id,
     p_category, trim(p_subject), trim(p_body), 'open', 'normal')
  returning id into v_id;

  insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
  values (
    v_actor, 'support_case.opened', 'support_case', v_id,
    jsonb_build_object('category', p_category, 'order_id', p_order_id,
                       'learner_profile_id', p_learner_profile_id)
  );

  return v_id;
end;
$$;
revoke execute on function public.open_support_case(text, text, text, uuid, uuid) from public;
grant execute on function public.open_support_case(text, text, text, uuid, uuid) to authenticated;

comment on function public.open_support_case(text, text, text, uuid, uuid) is
  'Opens a support case for the signed-in account. Refused while platform.support is off. Optional learner and order context must belong to the requester.';

-- -----------------------------------------------------------------------------
-- 6. Replying
-- -----------------------------------------------------------------------------

create or replace function public.reply_to_support_case(
  p_case_id     uuid,
  p_body        text,
  p_is_internal boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := public.current_user_id();
  v_case  public.support_cases;
  v_is_staff boolean;
  v_id    uuid;
begin
  if v_actor is null then
    raise exception 'sign in to reply' using errcode = 'insufficient_privilege';
  end if;

  select * into v_case from public.support_cases where id = p_case_id;
  if v_case.id is null then
    raise exception 'support case not found' using errcode = 'P0002';
  end if;

  if coalesce(trim(p_body), '') = '' then
    raise exception 'write a reply' using errcode = 'check_violation';
  end if;

  select public.is_privileged(v_actor) into v_is_staff;

  if not (v_is_staff or v_case.requested_by = v_actor) then
    raise exception
      'you cannot reply to somebody else''s case'
      using errcode = 'insufficient_privilege';
  end if;

  -- Only the team annotates. A requester asking for an internal note is asking
  -- to see something that is not theirs.
  if p_is_internal and not v_is_staff then
    raise exception
      'only staff may write an internal note'
      using errcode = 'insufficient_privilege';
  end if;

  if v_case.status = 'closed' then
    raise exception
      'this case is closed; open a new one if you still need help'
      using errcode = 'check_violation';
  end if;

  if not public.setting_bool('platform.support', false)
     and not v_is_staff then
    raise exception
      'support is not open right now (platform.support is off)'
      using errcode = 'check_violation';
  end if;

  insert into public.support_case_messages
    (case_id, author_user_id, author_kind, body, is_internal)
  values
    (p_case_id, v_actor, case when v_is_staff then 'staff' else 'requester' end,
     trim(p_body), coalesce(p_is_internal, false))
  returning id into v_id;

  -- A requester who answers a resolved case has said it is not resolved. A
  -- staff reply never changes the state; answering is not resolving.
  if not v_is_staff and not p_is_internal
     and v_case.status in ('resolved', 'waiting_on_user') then
    update public.support_cases
       set status = case when assigned_to is not null then 'assigned' else 'open' end,
           resolved_by = null, resolved_at = null, resolution_note = null
     where id = p_case_id;

    insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
    values (v_actor, 'support_case.reopened', 'support_case', p_case_id,
            jsonb_build_object('from_status', v_case.status));
  end if;

  insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
  values (
    v_actor,
    case when coalesce(p_is_internal, false)
         then 'support_case.internal_note' else 'support_case.replied' end,
    'support_case', p_case_id, '{}'::jsonb
  );

  return v_id;
end;
$$;
revoke execute on function public.reply_to_support_case(uuid, text, boolean) from public;
grant execute on function public.reply_to_support_case(uuid, text, boolean) to authenticated;

comment on function public.reply_to_support_case(uuid, text, boolean) is
  'Adds a message to a case. Staff may write internal notes; a requester reply to a resolved or waiting case reopens it.';

-- -----------------------------------------------------------------------------
-- 7. Working the queue
-- -----------------------------------------------------------------------------

create or replace function public.assign_support_case(
  p_case_id   uuid,
  p_assignee  uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := public.current_user_id();
  v_case  public.support_cases;
begin
  if v_actor is null or not public.is_privileged(v_actor) then
    raise exception 'only staff may assign a support case'
      using errcode = 'insufficient_privilege';
  end if;

  select * into v_case from public.support_cases where id = p_case_id;
  if v_case.id is null then
    raise exception 'support case not found' using errcode = 'P0002';
  end if;

  if not exists (select 1 from public.user_profiles where user_id = p_assignee) then
    raise exception 'that person cannot be assigned a case' using errcode = 'P0002';
  end if;

  if v_case.status in ('resolved', 'closed') then
    raise exception
      'a % case cannot be assigned; reopen it by replying first', v_case.status
      using errcode = 'check_violation';
  end if;

  update public.support_cases
     set assigned_to = p_assignee,
         assigned_by = v_actor,
         assigned_at = now(),
         status      = 'assigned'
   where id = p_case_id;

  insert into public.governance_audit_events (actor, action, target_type, target_id, detail)
  values (v_actor, 'support_case.assigned', 'support_case', p_case_id,
          jsonb_build_object('assignee', p_assignee));
end;
$$;
revoke execute on function public.assign_support_case(uuid, uuid) from public;
grant execute on function public.assign_support_case(uuid, uuid) to authenticated;

