#!/usr/bin/env node
// The shape of the `public` schema as the API sees it: every table and view
// with its columns, and every foreign key. Written to
// web/src/lib/postgrest-schema.snapshot.json, where
// web/src/lib/postgrest-select-contract.test.ts reads it to check each
// `.from(…).select(…)` in the application against the schema.
//
// Why: the pages cast what the API returns (`as unknown as Row[]`), so the
// compiler cannot tell that a column does not exist or that a relation is one
// object rather than a list. Until 2026-11-17 nothing spoke to a real
// PostgREST either, and reads asking for a missing column, naming a relation
// two foreign keys could mean, or indexing `[0]` into a single object all
// passed every check.
//
//   node scripts/postgrest-schema-snapshot.mjs           write the snapshot
//   node scripts/postgrest-schema-snapshot.mjs --check   fail if it is stale
//
// Built from supabase/tests/harness.sql and every migration, in PGlite.

import { PGlite } from '@electric-sql/pglite';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const target = join(root, 'web', 'src', 'lib', 'postgrest-schema.snapshot.json');

const db = new PGlite();
await db.exec(readFileSync(join(root, 'supabase', 'tests', 'harness.sql'), 'utf8'));
const files = readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort();
for (const f of files) {
  try {
    await db.exec(readFileSync(join(migrationsDir, f), 'utf8'));
  } catch (e) {
    console.error(`migration ${f} failed: ${String(e?.message ?? e).split('\n')[0]}`);
    process.exit(1);
  }
}

const relations = (await db.query(`
  select c.relname as name,
         case c.relkind when 'v' then 'view' when 'm' then 'view' else 'table' end as kind,
         (select array_agg(a.attname::text order by a.attnum)
            from pg_attribute a
           where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped) as columns
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm')
   order by 1`)).rows;

// `unique` is true when the referencing columns are themselves unique, which
// makes the relation one-to-one and an object from either side.
const foreignKeys = (await db.query(`
  select con.conname::text as name,
         cl.relname::text as "from",
         (select array_agg(a.attname::text order by k.ord)
            from unnest(con.conkey) with ordinality k(attnum, ord)
            join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum) as columns,
         case when fn.nspname = 'public' then fc.relname::text
              else fn.nspname || '.' || fc.relname end as "to",
         exists (
           select 1 from pg_index i
            where i.indrelid = con.conrelid and i.indisunique and i.indpred is null
              and (select array_agg(x order by x) from unnest(i.indkey::int2[]) x)
                  = (select array_agg(x order by x) from unnest(con.conkey) x)
         ) as "unique"
    from pg_constraint con
    join pg_class cl on cl.oid = con.conrelid
    join pg_namespace n on n.oid = cl.relnamespace
    join pg_class fc on fc.oid = con.confrelid
    join pg_namespace fn on fn.oid = fc.relnamespace
   where con.contype = 'f' and n.nspname = 'public'
   order by 2, 1`)).rows;
await db.close();

// One relation and one foreign key per line, so a migration's effect on the
// snapshot reads as a short diff.
const text = [
  '{',
  ' "note": "Generated by scripts/postgrest-schema-snapshot.mjs from the migrations. Do not edit by hand.",',
  ` "migrations": ${files.length},`,
  ` "lastMigration": ${JSON.stringify(files.at(-1))},`,
  ' "relations": {',
  relations.map((r) => `  ${JSON.stringify(r.name)}: ${JSON.stringify({ kind: r.kind, columns: r.columns })}`).join(',\n'),
  ' },',
  ' "foreignKeys": [',
  foreignKeys.map((k) => `  ${JSON.stringify(k)}`).join(',\n'),
  ' ]',
  '}',
  '',
].join('\n');
JSON.parse(text);

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('web/src/lib/postgrest-schema.snapshot.json does not match the migrations.');
    console.error('Run: node scripts/postgrest-schema-snapshot.mjs   and commit the result.');
    process.exit(1);
  }
  console.log(`schema snapshot is current: ${relations.length} relations, ${foreignKeys.length} foreign keys, ${files.length} migrations`);
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target}: ${relations.length} relations, ${foreignKeys.length} foreign keys, ${files.length} migrations`);
}
